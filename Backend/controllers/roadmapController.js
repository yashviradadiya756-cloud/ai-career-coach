const Roadmap = require("../models/Roadmap");
const Resume = require("../models/Resume");
const SkillGap = require("../models/SkillGap");
const Interview = require("../models/Interview");

const {
  generateContent,
} = require("../config/gemini");

/* =====================================================
   GENERATE ROADMAP
===================================================== */

const generateRoadmapController = async (
  req,
  res
) => {
  try {
    const { targetRole } = req.body;

    console.log(
      "===================================="
    );

    console.log(
      "GENERATE ROADMAP STARTED"
    );

    console.log(
      "USER:",
      req.user._id.toString()
    );

    console.log(
      "TARGET ROLE:",
      targetRole
    );

    console.log(
      "===================================="
    );

    /* =================================================
       VALIDATE ROLE
    ================================================= */

    if (
      !targetRole ||
      !targetRole.trim()
    ) {
      return res.status(400).json({
        success: false,

        message:
          "Target role is required",
      });
    }

    /* =================================================
       GET LATEST SKILL GAP
    ================================================= */

    const latestSkillGap =
      await SkillGap.findOne({
        user: req.user._id,
      }).sort({
        createdAt: -1,
      });

    console.log(
      "LATEST SKILL GAP:",
      latestSkillGap
        ? latestSkillGap._id
        : "NONE"
    );

    /* =================================================
       CHECK SKILL GAP
    ================================================= */

    if (!latestSkillGap) {
      return res.status(404).json({
        success: false,

        message:
          "Please complete Skill Gap Analysis before generating a roadmap.",
      });
    }

    /* =================================================
       GET MISSING SKILLS
    ================================================= */

    let missingSkills = [];

    if (
      Array.isArray(
        latestSkillGap.missingSkills
      )
    ) {
      missingSkills =
        latestSkillGap.missingSkills;
    }

    console.log(
      "MISSING SKILLS:"
    );

    console.log(
      missingSkills
    );

    /* =================================================
       GEMINI PROMPT
    ================================================= */

    const prompt = `
You are an expert AI Career Coach.

Create a learning roadmap specifically for the following target role.

TARGET ROLE:
${targetRole.trim()}

The candidate's missing skills are:

${
  missingSkills.length > 0
    ? missingSkills.join(", ")
    : "No missing skills available"
}

IMPORTANT RULES:

1. The roadmap MUST be specifically designed for the TARGET ROLE.

2. Do NOT generate a roadmap for another career.

3. If the target role is "Full Stack Developer", generate a Full Stack Developer roadmap.

4. Do NOT generate an AI/ML roadmap unless the target role explicitly contains:
AI, ML, Machine Learning, or Artificial Intelligence.

5. Use the missing skills to personalize the roadmap.

6. For Full Stack Development, include relevant topics such as:
frontend,
backend,
database,
APIs,
authentication,
deployment,
testing,
and projects.

7. Create 5 to 6 phases.

8. Each phase must contain useful topics.

9. Each phase must contain practical projects.

10. Each phase must contain learning resources.

11. Return ONLY valid JSON.

12. Do not use markdown.

13. Do not use code fences.

Return exactly this structure:

{
  "roadmapTitle": "string",
  "phases": [
    {
      "title": "string",
      "duration": "string",
      "topics": ["string"],
      "projects": ["string"],
      "resources": ["string"],
      "completed": false
    }
  ]
}
`;

    console.log(
      "GENERATING ROADMAP WITH GEMINI..."
    );

    /* =================================================
       GEMINI
    ================================================= */

    const response =
      await generateContent(
        prompt
      );

    let text =
      response.text;

    console.log(
      "RAW GEMINI RESPONSE:"
    );

    console.log(text);

    /* =================================================
       CLEAN JSON
    ================================================= */

    text = text
      .replace(/```json/g, "")
      .replace(/```/g, "")
      .trim();

    const roadmapData =
      JSON.parse(text);

    /* =================================================
       VALIDATE
    ================================================= */

    if (
      !roadmapData ||
      !Array.isArray(
        roadmapData.phases
      )
    ) {
      throw new Error(
        "Invalid roadmap generated by AI"
      );
    }

    /* =================================================
       SAVE ROADMAP
    ================================================= */

    const roadmap =
      await Roadmap.create({
        user: req.user._id,

        targetRole:
          targetRole.trim(),

        roadmapTitle:
          roadmapData.roadmapTitle ||
          `${targetRole} Career Roadmap`,

        phases:
          roadmapData.phases.map(
            (phase) => ({
              title:
                phase.title || "",

              duration:
                phase.duration || "",

              topics:
                Array.isArray(
                  phase.topics
                )
                  ? phase.topics
                  : [],

              projects:
                Array.isArray(
                  phase.projects
                )
                  ? phase.projects
                  : [],

              resources:
                Array.isArray(
                  phase.resources
                )
                  ? phase.resources
                  : [],

              completed:
                phase.completed ===
                true,
            })
          ),
      });

    console.log(
      "===================================="
    );

    console.log(
      "ROADMAP SAVED:"
    );

    console.log(
      roadmap._id
    );

    console.log(
      "===================================="
    );

    /* =================================================
       RESPONSE
    ================================================= */

    return res.status(201).json({
      success: true,

      message:
        "Roadmap generated successfully",

      roadmap,
    });

  } catch (error) {
    console.error(
      "===================================="
    );

    console.error(
      "ROADMAP GENERATION ERROR:"
    );

    console.error(error);

    console.error(
      "===================================="
    );

    return res.status(500).json({
      success: false,

      message:
        error.message ||
        "Failed to generate roadmap",
    });
  }
};

