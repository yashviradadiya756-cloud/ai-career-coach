/* =====================================================
   UPDATE PHASE COMPLETION
===================================================== */

const updatePhaseCompletionController =
  async (req, res) => {
    try {
      const {
        phaseId,
        completed,
      } = req.body;

      if (!phaseId) {
        return res.status(400).json({
          success: false,

          message:
            "Phase ID is required",
        });
      }

      const roadmap =
        await Roadmap.findOne({
          user: req.user._id,

          "phases._id": phaseId,
        });

      if (!roadmap) {
        return res.status(404).json({
          success: false,

          message:
            "Roadmap or phase not found",
        });
      }

      const phase =
        roadmap.phases.id(
          phaseId
        );

      phase.completed =
        completed === true;

      await roadmap.save();

      return res.status(200).json({
        success: true,

        message:
          phase.completed
            ? "Phase marked as completed"
            : "Phase marked as incomplete",

        roadmap,
      });

    } catch (error) {
      console.error(
        "UPDATE PHASE ERROR:",
        error
      );

      return res.status(500).json({
        success: false,

        message:
          error.message,
      });
    }
  };

/* =====================================================
   COACH DASHBOARD
===================================================== */

const getCoachDashboardController =
  async (req, res) => {
    try {
      const latestResume =
        await Resume.findOne({
          user: req.user._id,
        }).sort({
          createdAt: -1,
        });

      const resumeScore =
        latestResume
          ? Number(
              latestResume.atsScore
            ) || 0
          : 0;

      const latestRoadmap =
        await Roadmap.findOne({
          user: req.user._id,
        }).sort({
          createdAt: -1,
        });

      let roadmapProgress = 0;

      if (latestRoadmap) {
        const phases =
          latestRoadmap.phases ||
          [];

        if (phases.length > 0) {
          const completedPhases =
            phases.filter(
              (phase) =>
                phase.completed ===
                true
            ).length;

          roadmapProgress =
            Math.round(
              (completedPhases /
                phases.length) *
                100
            );
        }
      }

      const interviews =
        await Interview.find({
          user: req.user._id,
        }).sort({
          createdAt: -1,
        });

      const scores = [];

      for (const interview of interviews) {
        let score = null;

        if (
          interview.score !==
            undefined &&
          interview.score !== null
        ) {
          score = Number(
            interview.score
          );
        } else if (
          interview.overallScore !==
            undefined &&
          interview.overallScore !==
            null
        ) {
          score = Number(
            interview.overallScore
          );
        } else if (
          interview.percentage !==
            undefined &&
          interview.percentage !==
            null
        ) {
          score = Number(
            interview.percentage
          );
        }

        if (
          score !== null &&
          !Number.isNaN(score)
        ) {
          score = Math.max(
            0,
            Math.min(100, score)
          );

          scores.push(score);
        }
      }

      let interviewScore = 0;

      if (scores.length > 0) {
        const total =
          scores.reduce(
            (sum, score) =>
              sum + score,
            0
          );

        interviewScore =
          Math.round(
            total / scores.length
          );
      }

      const careerScore =
        Math.round(
          (
            resumeScore +
            roadmapProgress +
            interviewScore
          ) / 3
        );

      return res.status(200).json({
        success: true,

        scores: {
          careerScore,
          roadmapProgress,
          resumeScore,
          interviewScore,
        },
      });

    } catch (error) {
      console.error(
        "COACH DASHBOARD ERROR:",
        error
      );

      return res.status(500).json({
        success: false,

        message:
          error.message,
      });
    }
  };

